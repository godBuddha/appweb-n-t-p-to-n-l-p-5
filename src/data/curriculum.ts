export function getQuestionsForMode(mode: PracticeMode): Question[] {
  if (mode === 'daily') {
    const domains: MathDomain[] = ['fractions', 'decimals', 'geometry', 'measurement'];
    return domains
      .map((d) => CURRICULUM_QUESTIONS.find((q) => q.domain === d))
      .filter((q): q is Question => Boolean(q));
  }
  if (mode === 'de-1' || mode === 'de-2' || mode === 'de-3' || mode === 'de-4') {
    return CURRICULUM_QUESTIONS.filter((q) => q.examPaper === mode);
  }
  return CURRICULUM_QUESTIONS.filter((q) => q.domain === mode);
}
